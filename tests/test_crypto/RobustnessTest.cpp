/**
 * @brief Fills a buffer with a repeating pattern, so a test never depends on uninitialised memory.
 *
 * @param size Number of bytes to produce.
 * @param seed Value of the first byte.
 * @return The generated bytes.
 */
std::vector<std::byte> pattern(std::size_t size, unsigned seed = 0)
{
    std::vector<std::byte> out(size);
    for (std::size_t index = 0; index < size; ++index) {
        out[index] = static_cast<std::byte>((index + seed) & 0xFFu);
    }
    return out;
}

