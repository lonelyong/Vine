TEST(CryptoRobustnessTest, RandomIsSafeUnderConcurrentUse)
{
    // The process-wide DRBG is serialised by a mutex; this proves that claim with 4 threads pulling 32 values each.
    constexpr std::size_t kThreads  = 4;
    constexpr std::size_t kPerThread = 32;

    std::mutex                        guard;
    std::set<std::vector<std::byte>>  seen;
    std::vector<std::thread>          workers;

    for (std::size_t thread = 0; thread < kThreads; ++thread) {
        workers.emplace_back([&guard, &seen] {
            for (std::size_t index = 0; index < kPerThread; ++index) {
                const auto value = Random::bytes(16);
                const std::lock_guard<std::mutex> lock(guard);
                seen.insert(value);
            }
        });
    }
    for (auto& worker : workers) {
        worker.join();
    }

    // 128 values of 16 bytes: a repeat would mean the generator handed out the same block twice.
    EXPECT_EQ(seen.size(), kThreads * kPerThread);
}

TEST(CryptoRobustnessTest, AesGcmAcceptsEveryDefinedKeyAndIvSize)
{
    const auto plaintext = pattern(96);

    for (const std::size_t keySize : { 16u, 24u, 32u }) {
        for (const std::size_t ivSize : { 1u, 12u, 16u }) {
            const auto key    = Random::bytes(keySize);
            const auto iv     = Random::bytes(ivSize);
            const auto sealed = AesGcm::seal(key, iv, plaintext);
            EXPECT_EQ(AesGcm::open(key, iv, sealed.ciphertext, sealed.tag), plaintext)
                << "key " << keySize << ", iv " << ivSize;
        }
    }
}

TEST(CryptoRobustnessTest, AesGcmRejectsOutOfRangeParameters)
{
    const auto key = Random::bytes(16);
    const auto iv  = Random::bytes(12);

    EXPECT_THROW(AesGcm::encryptor(std::span<const std::byte>(), iv), std::invalid_argument);
    EXPECT_THROW(AesGcm::encryptor(Random::bytes(15), iv), std::invalid_argument);
    EXPECT_THROW(AesGcm::encryptor(Random::bytes(33), iv), std::invalid_argument);
    EXPECT_THROW(AesGcm::encryptor(key, std::span<const std::byte>()), std::invalid_argument);

    // The tag is always 16 bytes: a 15- or 17-byte tag is a caller bug, not something to truncate.
    EXPECT_THROW(AesGcm::decryptor(key, iv, Random::bytes(15)), std::invalid_argument);
    EXPECT_THROW(AesGcm::decryptor(key, iv, Random::bytes(17)), std::invalid_argument);
}

TEST(CryptoRobustnessTest, IncrementalObjectsSurviveMoveAndRejectReuse)
{
    const auto message = pattern(200, 7);

    // Move in the middle of a computation: the state must travel with the object.
    Hasher hasher(Digest::kSha256);
    hasher.update(std::span<const std::byte>(message).first(100));
    Hasher movedHasher = std::move(hasher);
    movedHasher.update(std::span<const std::byte>(message).subspan(100));

    const auto expected = vn::crypto::digest(Digest::kSha256, message);
    EXPECT_EQ(movedHasher.finish(), expected);
    EXPECT_EQ(movedHasher.finish(), expected); // cached
    EXPECT_THROW(movedHasher.update(message), std::logic_error);

    // The same for HMAC, which carries a keyed context instead of a plain one.
    const auto key = Random::bytes(32);
    Hmac       mac(Digest::kSha256, key);
    mac.update(std::span<const std::byte>(message).first(50));
    Hmac movedMac = std::move(mac);
    movedMac.update(std::span<const std::byte>(message).subspan(50));
    EXPECT_EQ(movedMac.finish(), vn::crypto::hmac(Digest::kSha256, key, message));
    EXPECT_THROW(movedMac.update(message), std::logic_error);
}

TEST(CryptoRobustnessTest, HkdfBoundedLengthsWork)
{
    const auto ikm = Random::bytes(32);

    // One byte is the smallest legal output; 255 blocks is the RFC ceiling.
    EXPECT_EQ(Hkdf::derive(Digest::kSha256, ikm, {}, {}, 1).size(), 1u);
    EXPECT_EQ(Hkdf::derive(Digest::kSha256, ikm, {}, {}, 255 * 32).size(), 255u * 32u);

    // A longer digest allows a longer output, which is what the ceiling is tied to.
    EXPECT_EQ(Hkdf::derive(Digest::kSha512, ikm, {}, {}, 255 * 64).size(), 255u * 64u);
    EXPECT_THROW(Hkdf::derive(Digest::kSha512, ikm, {}, {}, 255 * 64 + 1), std::invalid_argument);

    // extract and expand must agree on the digest, and a different digest must give a different PRK.
    EXPECT_NE(Hkdf::extract(Digest::kSha256, {}, ikm), Hkdf::extract(Digest::kSha384, {}, ikm));
}

TEST(CryptoRobustnessTest, PemImporterRejectsMalformedText)
{
    const auto key     = RsaKey::generate(2048);
    const auto goodPem = key.toPrivatePem();

    // Truncating the armour, feeding a private block to a public importer, and feeding non-base64 all fail loudly.
    const std::u8string truncated = goodPem.substr(0, goodPem.size() / 2);
    EXPECT_THROW(RsaKey::fromPrivatePem(truncated), std::invalid_argument);
    EXPECT_THROW(RsaKey::fromPublicPem(goodPem), std::invalid_argument);

    const std::u8string notBase64 = u8"-----BEGIN RSA PRIVATE KEY-----\n!!!!\n-----END RSA PRIVATE KEY-----\n";
    EXPECT_THROW(RsaKey::fromPrivatePem(notBase64), std::invalid_argument);

    // An EC importer must not accept an RSA block either, even though both are valid PEM.
    EXPECT_THROW(EccKey::fromPrivatePem(goodPem), std::invalid_argument);
}

TEST(CryptoRobustnessTest, KeysRejectValuesOutsideTheirContract)
{
    // A signature from one key must not verify under another, and a ciphertext must not decrypt under another.
    const auto first  = RsaKey::generate(2048);
    const auto second = RsaKey::generate(2048);
    const auto msg    = pattern(32);

    EXPECT_FALSE(second.verify(msg, first.sign(msg)));
    EXPECT_THROW(second.decrypt(first.encrypt(msg)), std::runtime_error);

    // ECDH across curves is a programming error, not an empty answer.
    const auto p256 = EccKey::generate(EccKey::Curve::kP256);
    const auto p384 = EccKey::generate(EccKey::Curve::kP384);
    EXPECT_THROW(p256.sharedSecret(p384), std::invalid_argument);

    // A DER blob that is not a key at all must be reported as such.
    EXPECT_THROW(EccKey::fromPublicDer(pattern(64)), std::invalid_argument);
    EXPECT_THROW(RsaKey::fromPublicDer(pattern(64)), std::invalid_argument);
}
